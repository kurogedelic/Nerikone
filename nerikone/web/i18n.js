const PUNCT = {'（': ' (', '）': ')', '、': ', ', '。': '. ', '・': ' / ', '：': ': ', '？': '?', '　': ' ', '〜': '~', '「': '"', '」': '"'};

const keys = Object.keys(EN).sort((a, b) => b.length - a.length);
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RX = new RegExp(keys.map(esc).join('|'), 'g');
const JP = /[　-鿿＀-￯]/;
export function tr(s) {
  if (LANG !== 'en' || typeof s !== 'string' || !JP.test(s)) return s;
  return s.replace(RX, m => EN[m]).replace(/[（）、。・：？　〜「」]/g, c => PUNCT[c]).replace(/ {2,}/g, ' ').replace(/\( /g, '(');
}

const ATTRS = ['data-tip', 'data-sub', 'placeholder', 'title', 'aria-label'];
function setAttr(el, a) { // only when it changes: a write fires the observer again
  const v = el.getAttribute(a);
  if (v && JP.test(v)) { const t = tr(v); if (t !== v) el.setAttribute(a, t); }
}
function walk(node) {
  if (node.nodeType === 3) { if (JP.test(node.data)) { const t = tr(node.data); if (t !== node.data) node.data = t; } return; }
  if (node.nodeType !== 1 || node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
  for (const a of ATTRS) setAttr(node, a);
  for (let c = node.firstChild; c; c = c.nextSibling) walk(c);
}
export function startTranslating() {
  if (LANG !== 'en') return;
  document.documentElement.lang = 'en';
  walk(document.body);
  new MutationObserver(list => {
    for (const m of list) {
      if (m.type === 'characterData') walk(m.target);
      else if (m.type === 'attributes') setAttr(m.target, m.attributeName);
      else m.addedNodes.forEach(walk);
    }
  }).observe(document.body, {subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS});
  // dialogs the page opens itself
  const {confirm: c0, prompt: p0, alert: a0} = window;
  window.confirm = m => c0.call(window, tr(m));
  window.prompt = (m, d) => p0.call(window, tr(m), d);
  window.alert = m => a0.call(window, tr(m));
}
